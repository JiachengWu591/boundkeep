def _bare_lookup(name: str) -> str | None:
    """Alias or canonical name (any case) of an ASCII name; None otherwise."""
    if not name.isascii():
        return None
    low = name.lower()
    return ALIASES.get(low) or _CANON.get(low)


def canonical_command(name: str) -> str | None:
    """The canonical form of a command name, or None when this module does not know it.

    * an alias (``rm``, ``%``, ``curl``...) gives its target in canonical case (``Remove-Item``);
    * a canonical cmdlet / function name in any case gives the canonical spelling;
    * ``Microsoft.PowerShell.Management\\Remove-Item`` (a built-in module name, a single backslash,
      then a canonical cmdlet name) gives ``Remove-Item``; other module prefixes are NOT resolved
      (a user module could shadow the cmdlet) and come back unchanged like paths;
    * a name with a path separator (``/`` or ``\\``) or an ``.exe`` extension is an external
      program: it is returned UNCHANGED (the caller strips or handles it);
    * anything else (unknown names, control characters, non-ASCII bare names, too long): None.

    Never raises. Matching never uses locale-dependent case folding (ASCII only).
    """
    if not isinstance(name, str) or not name or len(name) > _MAX_NAME:
        return None
    if _CTRL_RE.search(name):
        return None
    if "\\" in name or "/" in name:
        module, sep, leaf = name.partition("\\")
        if sep and module.lower() in _BUILTIN_MODULES and "\\" not in leaf and "/" not in leaf:
            low = leaf.lower() if leaf.isascii() else ""
            if low in _CANON:
                return _CANON[low]
        return name
    found = _bare_lookup(name)
    if found is not None:
        return found
    if len(name) > 4 and name[-4:].lower() == ".exe":
        return name
    return None


def cmdlet_spec(name: str) -> CmdletSpec | None:
    """The :class:`CmdletSpec` for a command name (alias, any case, module-qualified); None when
    the command is unknown or has no parameter table. Never raises."""
    canon = canonical_command(name)
    if canon is None:
        return None
    return CMDLETS.get(canon.lower())


def is_cmdlet_shaped(name: str) -> bool:
    """True for a ``Verb-Noun`` identifier: unknown ones are probably cmdlets of a module this
    table does not cover (the caller may prefer gray over "unknown external program")."""
    return bool(
        isinstance(name, str)
        and len(name) < 128
        and re.fullmatch(r"[A-Za-z]+-[A-Za-z][A-Za-z0-9]*", name)
    )


def canonical_param(cmdlet: str, token: str) -> str | _Ambiguous | None:
    """Resolve the parameter token of a command to its canonical name WITH a leading dash.

    ``cmdlet`` may be an alias or any-case name (resolved with :func:`canonical_command`);
    ``token`` is the parameter as written (``-rec``, ``Recurse``; one leading ``-`` is optional).
    A token containing ``:`` is not valid input (split ``-Name:value`` first): it gives None.

    * the full name or an alias of a parameter (``-cf`` -> ``-Confirm``);
    * a unique abbreviation (``-Rec`` -> ``-Recurse``), following PowerShell's rule (see
      :meth:`CmdletSpec.resolve`): an exact name/alias wins over prefixes, a prefix that matches
      both a name and an alias of the SAME parameter is not ambiguous, and when a prefix fits
      several parameters but exactly one of them is declared by the command itself, that one wins;
    * ``AMBIGUOUS`` when several parameters remain;
    * ``None`` for an unknown cmdlet, an unknown parameter, or a token that is not a plain ASCII
      parameter name (empty, too long, non-ASCII, punctuation).

    Never raises.
    """
    if not isinstance(cmdlet, str) or not isinstance(token, str) or len(token) > _MAX_TOKEN + 1:
        return None
    spec = cmdlet_spec(cmdlet)
    if spec is None:
        return None
    t = _strip_dash(token)
    if not _TOKEN_RE.fullmatch(t):
        return None
    hit = spec.resolve(t)
    if hit is None:
        return None
    if isinstance(hit, _Ambiguous):
        return AMBIGUOUS
    return "-" + hit.name


def takes_value(cmdlet: str, canonical_param: str) -> bool | None:
    """Whether the parameter consumes the next word: True for value parameters, False for
    switches, None when the cmdlet or the parameter is unknown (the caller must not guess).

    ``canonical_param`` is a canonical name (with or without the leading dash) or an alias; no
    abbreviations. Never raises.
    """
    if not isinstance(cmdlet, str) or not isinstance(canonical_param, str):
        return None
    if len(canonical_param) > _MAX_TOKEN + 1:
        return None
    spec = cmdlet_spec(cmdlet)
    if spec is None:
        return None
    p = spec.param(canonical_param)
    if p is None:
        return None
    return not p.switch
