"""Static knowledge of PowerShell command aliases and cmdlet parameters.

This module is DATA plus pure lookups. Importing it never starts PowerShell, never touches the file
system and never reads the environment. The data comes from a real Windows PowerShell 5.1 and is
regenerated by ``scripts/gen_ps_aliases.py`` (which also prints a diff against the checked-in
tables); ``tests/unit/test_norm_psaliases.py`` re-checks it against the live machine on Windows.

Source of the data (Windows only; the same build was used for every table)::

    Microsoft Windows NT 10.0.26200.0, Windows PowerShell 5.1.26100.9444 (build 10.0.26100.9444)

Design rules (docs/m1-design.md "底线", docs/m1b-design.md section 5):

* Facts only. An alias that hides ``Remove-Item`` or a parameter abbreviation that is resolved
  wrongly would let a destructive command look harmless, so every lookup FAILS TOWARD UNKNOWN:
  ``None`` (not known) or ``AMBIGUOUS`` (several candidates), never a guess. Callers turn both into
  a gray verdict.
* Everything is total: any ``str`` (NUL, lone surrogates, a megabyte of text) gives a result, never
  an exception; non-ASCII names and parameter tokens are never resolved (PowerShell compares names
  with culture-aware rules that ignore some invisible characters; we do not model that, so such a
  token is "unknown").
* The alias table is the one of Windows PowerShell 5.1 (what ``powershell.exe`` runs). PowerShell 7
  (``pwsh``) differs: ``curl`` / ``wget`` / ``sc`` are not aliases there
  (``NAMES_DIFFERENT_IN_PS7``) and a few Windows-only aliases are gone. Callers that know the
  engine is ``pwsh`` must treat those three names as unknown.

API (docs/m1b-design.md section 5; additions are allowed, renames are not)::

    ALIASES              lowercase alias -> canonical command name
    CMDLETS              lowercase canonical name -> CmdletSpec
    canonical_command()  alias / any-case / module-qualified name -> canonical name; ``x.exe`` and
                         names with a path separator come back unchanged; anything else None
    canonical_param()    ``-Rec`` -> ``-Recurse``; None (unknown) or AMBIGUOUS
    takes_value()        True / False / None (unknown)
"""

