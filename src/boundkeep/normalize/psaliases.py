def _parse_alias_rows(data: str) -> dict[str, str]:
    out: dict[str, str] = {}
    for line in data.splitlines():
        if not line.strip():
            continue
        parts = line.split(" ")
        if len(parts) != 2 or not all(parts):
            raise ValueError(f"bad alias row {line!r}")
        alias, target = parts
        if alias != alias.lower() or not alias.isascii() or alias in out:
            raise ValueError(f"bad alias row {line!r}")
        out[alias] = target
    return out


def _parse_param(line: str, group: str) -> ParamSpec:
    name, *toks = line.split()
    aliases: tuple[str, ...] = ()
    positions: tuple[int, ...] = ()
    switch = wild = rest = dyn = False
    path: Access | None = None
    for tok in toks:
        if tok.startswith("a="):
            aliases = tuple(tok[2:].split(","))
        elif tok.startswith("pos="):
            positions = tuple(int(i) for i in tok[4:].split(","))
        elif tok == "switch":
            switch = True
        elif tok == "wild":
            wild = True
        elif tok == "rest":
            rest = True
        elif tok == "dyn":
            dyn = True
        elif tok == "read":
            path = "read"
        elif tok == "write":
            path = "write"
        elif tok == "unknown":
            path = "unknown"
        elif tok in ("common", "sp", "tx", "pg"):
            group = tok
        else:
            raise ValueError(f"bad parameter token {tok!r} in {line!r}")
    return ParamSpec(
        name=name,
        aliases=aliases,
        switch=switch,
        position=min(positions) if positions else None,
        positions=positions,
        wildcards=wild,
        path=path,
        dynamic=dyn,
        rest=rest,
        group=group,
    )


def _parse_common(data: str) -> tuple[ParamSpec, ...]:
    return tuple(_parse_param(line, "common") for line in data.splitlines() if line.strip())


COMMON_PARAMETERS: Final[tuple[ParamSpec, ...]] = _parse_common(_COMMON_DATA)


def _parse_cmdlets(data: str) -> dict[str, CmdletSpec]:
    out: dict[str, CmdletSpec] = {}
    header: list[str] | None = None
    declared: list[ParamSpec] = []

    def flush() -> None:
        if header is None:
            return
        name, *flags = header
        unknown = set(flags) - {"function", "sp", "tx", "nocommon"}
        if unknown or name.lower() in out:
            raise ValueError(f"bad cmdlet header {header!r}")
        params = list(declared)
        if "nocommon" not in flags:
            for p in COMMON_PARAMETERS:
                if p.group == "sp" and "sp" not in flags:
                    continue
                if p.group == "tx" and "tx" not in flags:
                    continue
                params.append(p)
        out[name.lower()] = CmdletSpec(
            name=name,
            params=tuple(params),
            kind="function" if "function" in flags else "cmdlet",
        )

    rows: list[str] = []
    for line in data.splitlines():
        if not line.strip():
            continue
        if line.startswith("    ") and rows:  # continuation of a long parameter row
            rows[-1] += " " + line.strip()
        else:
            rows.append(line)
    for line in rows:
        if line[0] != " ":
            flush()
            header = line.split()
            declared = []
        else:
            declared.append(_parse_param(line, "declared"))
    flush()
    return out


CMDLETS: Final[dict[str, CmdletSpec]] = _parse_cmdlets(_CMDLET_DATA)

CORE_ALIASES: Final[dict[str, str]] = _parse_alias_rows(_CORE_ALIAS_DATA)
AUTOLOAD_ALIASES: Final[dict[str, str]] = _parse_alias_rows(_AUTOLOAD_ALIAS_DATA)
#: Every alias (lowercase) -> canonical command name. Core aliases win over auto-loaded ones.
ALIASES: Final[dict[str, str]] = {**AUTOLOAD_ALIASES, **CORE_ALIASES}

#: Alias targets that are programs, not cmdlets (``ise`` -> ``powershell_ise.exe``).
EXTERNAL_TARGETS: Final = frozenset(t for t in ALIASES.values() if t.lower().endswith(".exe"))

#: Canonical command names that are known to exist but have no parameter table here
#: (lowercase -> canonical). ``canonical_param`` answers None for them: callers go gray.
UNMODELED: Final[dict[str, str]] = {
    n.lower(): n
    for n in (*_UNMODELED_DATA.split(), *_PS7_ONLY)
    if n.lower() not in CMDLETS and not n.lower().endswith(".exe")
}

_CANON: Final[dict[str, str]] = {**UNMODELED, **{k: v.name for k, v in CMDLETS.items()}}


