@dataclass(frozen=True, slots=True)
class ParamSpec:
    """One parameter of a cmdlet.

    ``position`` is the lowest positional index over all parameter sets (None: named only);
    ``positions`` lists every index the parameter has in some set (more than one means the position
    depends on the parameter set the command binds: treat positional arguments of that cmdlet as
    not resolvable). ``path`` is how the value is accessed when the parameter names a path
    (``"read"``, ``"write"``, ``"unknown"``: may be either) or None when it is not a path.
    ``wildcards`` means the value MAY be treated as a wildcard pattern by the cmdlet (``-Path``,
    ``-Include``, ``-Name`` of ``Stop-Process``...; never ``-LiteralPath``). Windows PowerShell 5.1
    does not expose this for compiled cmdlets, so the flag is hand-assigned and conservative: a
    path parameter is ``wildcards`` unless it is known to be literal-only.
    ``dynamic`` marks provider parameters (``-File`` of the FileSystem provider, ``-Type`` of the
    Registry provider...): they only exist for some paths, but they take part in abbreviation
    matching, so they are listed. ``rest`` means the parameter swallows all remaining positional
    arguments. ``group`` is ``declared`` (the command's own parameter), ``common``
    (``-Verbose``...), ``sp`` (``-WhatIf`` / ``-Confirm``), ``tx`` (``-UseTransaction``) or ``pg``
    (``-First`` / ``-Skip`` / ``-IncludeTotalCount`` of a cmdlet that supports paging).
    """

    name: str
    aliases: tuple[str, ...] = ()
    switch: bool = False
    position: int | None = None
    positions: tuple[int, ...] = ()
    wildcards: bool = False
    path: Access | None = None
    dynamic: bool = False
    rest: bool = False
    group: str = "declared"

    @property
    def position_conflict(self) -> bool:
        """True when the position differs between parameter sets."""
        return len(self.positions) > 1


@dataclass(frozen=True, slots=True)
class CmdletSpec:
    """A cmdlet (or function) with every parameter it accepts, common ones included."""

    name: str
    params: tuple[ParamSpec, ...]
    kind: str = "cmdlet"  # "cmdlet" | "function"
    _names: dict[str, ParamSpec] = field(default_factory=dict, repr=False, compare=False)
    _aliases: dict[str, ParamSpec] = field(default_factory=dict, repr=False, compare=False)

    def __post_init__(self) -> None:
        for p in self.params:
            self._names.setdefault(p.name.lower(), p)
        for p in self.params:
            for a in p.aliases:
                self._aliases.setdefault(a.lower(), p)

    def param(self, name: str) -> ParamSpec | None:
        """The parameter with exactly this canonical name or alias (any case, leading ``-``
        optional); None otherwise. No abbreviations: see :func:`canonical_param`."""
        key = _strip_dash(name).lower()
        return self._names.get(key) or self._aliases.get(key)

    def positional(self) -> tuple[ParamSpec, ...]:
        """The parameters that can be bound by position, ordered by position (then name)."""
        pos = [p for p in self.params if p.position is not None]
        return tuple(sorted(pos, key=lambda p: (p.position or 0, p.name.lower())))

    @property
    def position_conflict(self) -> bool:
        """True when some parameter's position depends on the parameter set (see ParamSpec)."""
        return any(p.position_conflict for p in self.params)

    def resolve(self, token: str) -> ParamSpec | _Ambiguous | None:
        """PowerShell's parameter-name resolution for a bare ASCII ``token`` (no dash, no colon).

        The real rule (``MergedCommandParameterMetadata.GetMatchingParameter``, verified against
        ``CommandInfo.ResolveParameter`` by the Windows tests): an exact parameter name wins, then
        an exact alias; otherwise the candidates are the DISTINCT parameters having a name or an
        alias that starts with the token; one candidate wins; with several, those declared by the
        command itself (not common / ``-WhatIf`` / ``-Confirm`` / ``-UseTransaction``) are
        preferred if exactly one of them remains; otherwise the token is ambiguous. One deliberate
        deviation, toward AMBIGUOUS: a winner that is a provider (dynamic) parameter is not trusted
        when other candidates exist (see below).
        """
        t = token.lower()
        cands: dict[str, ParamSpec] = {}
        for key, p in self._names.items():
            if key.startswith(t):
                cands[p.name] = p
        for key, p in self._aliases.items():
            if key.startswith(t):
                cands[p.name] = p
        hit = self._names.get(t) or self._aliases.get(t)
        if hit is not None:
            # An exact provider parameter only exists for some paths (``-D`` is the alias of the
            # FileSystem ``-Directory``, but ``-Depth`` elsewhere): trusted only when nothing else
            # starts with the token.
            return AMBIGUOUS if hit.dynamic and len(cands) > 1 else hit
        if not cands:
            return None
        if len(cands) == 1:
            return next(iter(cands.values()))
        declared = [p for p in cands.values() if p.group == "declared"]
        if len(declared) == 1 and not declared[0].dynamic:
            return declared[0]
        # Several candidates and either none or several of them are the command's own, or the
        # only declared one is a provider (dynamic) parameter: with another provider path the same
        # abbreviation would bind a different parameter, and the provider is not known here.
        return AMBIGUOUS


